using System.Net;
using ACA360.Tests.Integration.Infrastructure;

namespace ACA360.Tests.Integration;

/// <summary>Errors System Health showed recurring (2026-10-06), kept fixed.</summary>
[Collection(AppCollection.Name)]
public class BugFixTests : IDisposable
{
    private readonly AcaWebFactory _app;

    public BugFixTests(AcaWebFactory app) => _app = app;

    public void Dispose()
    {
        TestEmployees.RemoveAll();
        TestImports.RemoveAll();
    }

    /// <summary>
    /// Risk Analysis on a page without an employer asked for employer 0, year 0, and reading the
    /// risk generated the codes whenever none had a January code. Reading now changes nothing.
    /// </summary>
    [LocalDbFact]
    public async Task ReadingThePenaltyRiskChangesNothing()
    {
        var employer = TestImports.CreateEmployer(2025);
        var person = TestEmployees.Create(employer.Id, 2025, "RISKREAD");     // codes kept for all 12 months only
        using var admin = await _app.SignedInAs(TestUsers.CreateStaff(RoleIds.SuperAdmin, "risk-read"));

        var none = await admin.JsonAsync("/FormGeneration/GetRiskAnalysis?employerId=0&year=0");
        Assert.True(none.GetProperty("codesMissing").GetBoolean());

        string Codes() => LocalDb.Scalar<string>("SELECT CONCAT(ALLM_COC, '/', JAN_COC) FROM dbo.EmployeeCode WHERE employeeId = @id", new { id = person.Id });
        var before = Codes();
        var risk = await admin.JsonAsync($"/FormGeneration/GetRiskAnalysis?employerId={employer.Id}&year=2025");
        Assert.False(risk.GetProperty("codesMissing").GetBoolean());
        Assert.Equal(before, Codes());   // not regenerated

        // An employer without codes is told so, and nothing is generated by looking.
        var empty = TestImports.CreateEmployer(2025);
        var page = await (await admin.PageAsync($"/ACA/PenaltyRisk?employerId={empty.Id}&year=2025")).Content.ReadAsStringAsync();
        Assert.Contains("have not been generated", page);
        Assert.Equal(0, LocalDb.Scalar<int>("SELECT COUNT(*) FROM dbo.EmployeeCode WHERE employerId = @id", new { id = empty.Id }));
    }

    /// <summary>The employer details tab failed on a missing id, answered any employer, and sent the stack trace.</summary>
    [LocalDbFact]
    public async Task TheEmployerDetailsTabNeedsAnEmployerTheUserMaySee()
    {
        var employer = TestImports.CreateEmployer(2025);
        using var am = await _app.SignedInAs(TestUsers.CreateStaff(RoleIds.AccountManager, "details-tab"));
        var missing = await am.AjaxAsync("/Employer/EmployerOtherDetailsPartial");
        Assert.Equal(HttpStatusCode.BadRequest, missing.StatusCode);
        Assert.DoesNotContain("   at ", await missing.Content.ReadAsStringAsync());
        Assert.Equal(HttpStatusCode.Forbidden, (await am.AjaxAsync($"/Employer/EmployerOtherDetailsPartial?aca_employerId={employer.Id}")).StatusCode);

        using var admin = await _app.SignedInAs(TestUsers.CreateStaff(RoleIds.SuperAdmin, "details-tab-admin"));
        Assert.Equal(HttpStatusCode.OK, (await admin.AjaxAsync($"/Employer/EmployerOtherDetailsPartial?aca_employerId={employer.Id}")).StatusCode);
    }

    /// <summary>View As was never audited: its detail was plain text and the audit table takes JSON only.</summary>
    [LocalDbFact]
    public async Task ViewAsIsAudited()
    {
        var employer = TestImports.CreateEmployer(2025);
        var admin = TestUsers.CreateStaff(RoleIds.SuperAdmin, "viewas-audit");
        using var client = await _app.SignedInAs(admin);
        var begun = await client.PostFormAsync("/ViewAs/Begin", "/Calendar/Index",
            new Dictionary<string, string> { ["mode"] = "Employer", ["targetId"] = employer.Id.ToString() }, ajax: true);
        Assert.Equal(HttpStatusCode.OK, begun.StatusCode);
        try
        {
            var detail = LocalDb.Scalar<string?>(
                "SELECT TOP 1 New_Values FROM dbo.DataAuditlog WHERE Table_Name = 'ViewAs' AND User_Id = @u ORDER BY Created_at DESC",
                new { u = admin.UserId.ToString() });
            Assert.NotNull(detail);
            Assert.Contains($"Employer:{employer.Id}", detail);
        }
        finally
        {
            await client.PostFormAsync("/ViewAs/End", "/Calendar/Index", new Dictionary<string, string>(), ajax: true);
            LocalDb.Execute("DELETE FROM dbo.DataAuditlog WHERE Table_Name = 'ViewAs' AND User_Id = @u", new { u = admin.UserId.ToString() });
        }
    }
}
